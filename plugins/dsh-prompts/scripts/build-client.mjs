import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const read = (path) => readFileSync(new URL(path, root), "utf8");

const languages = ["en", "zh", "de", "fr", "es", "ja", "ko", "pt"];
const placeholders = (value) => [...String(value).matchAll(/\{(\w+)\}/g)].map((match) => match[1]).sort();

// 1. Validate static bundle locale/*.json files
const staticDictionaries = {};
for (const file of readdirSync(new URL("locale/", root)).filter((f) => f.endsWith(".json")).sort()) {
  staticDictionaries[file.slice(0, -5)] = JSON.parse(read(`locale/${file}`));
}
if (languages.some((id) => !staticDictionaries[id]) || Object.keys(staticDictionaries).length !== languages.length) {
  throw new Error("All eight static locale/*.json files are required");
}
for (const [id, dict] of Object.entries(staticDictionaries)) {
  if (typeof dict?.meta?.title !== "string" || !dict.meta.title.trim()) {
    throw new Error(`Missing static meta.title in locale/${id}.json`);
  }
  if (typeof dict?.meta?.description !== "string" || !dict.meta.description.trim()) {
    throw new Error(`Missing static meta.description in locale/${id}.json`);
  }
}

// 2. Validate runtime lib/locales/*.json dictionaries
const dictionaries = {};
for (const file of readdirSync(new URL("lib/locales/", root)).filter((f) => f.endsWith(".json")).sort()) {
  dictionaries[file.slice(0, -5)] = JSON.parse(read(`lib/locales/${file}`));
}
if (languages.some((id) => !dictionaries[id]) || Object.keys(dictionaries).length !== languages.length) {
  throw new Error("All eight runtime locale dictionaries in lib/locales/ are required");
}
const keys = Object.keys(dictionaries.en).sort();
for (const [id, dictionary] of Object.entries(dictionaries)) {
  if (JSON.stringify(Object.keys(dictionary).sort()) !== JSON.stringify(keys)) {
    throw new Error(`Locale key mismatch in lib/locales/${id}.json`);
  }
  for (const key of keys) {
    if (typeof dictionary[key] !== "string" || !dictionary[key].trim()) {
      throw new Error(`Missing translation: ${id}.${key}`);
    }
    if (JSON.stringify(placeholders(dictionary[key])) !== JSON.stringify(placeholders(dictionaries.en[key]))) {
      throw new Error(`Locale placeholders differ: ${id}.${key}`);
    }
  }
}

const model = read("lib/model.cjs").trim();
let source = read("src/client.js");
source = source.replace(
  "__PROMPTS_MODEL__",
  () => `(() => { const module = { exports: {} };\n${model}\nreturn module.exports; })()`
);
source = source.replace("__PROMPTS_LOCALES__", () => JSON.stringify(dictionaries, null, 2));

const output =
  "// Generated by scripts/build-client.mjs from src/client.js, lib/model.cjs and lib/locales.\n" + source;
const target = new URL("lib/client.js", root);

if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) {
    throw new Error("Client bundle is stale: run npm run build");
  }
} else {
  writeFileSync(target, output);
}
console.log(`${process.argv.includes("--check") ? "Checked" : "Built"} ${fileURLToPath(target)}`);
