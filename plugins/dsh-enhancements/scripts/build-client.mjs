import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const read = path => readFileSync(new URL(path, root), "utf8");
const dictionaries = {};
for (const file of readdirSync(new URL("lib/locales/", root)).filter(file => file.endsWith(".json")).sort()) {
  dictionaries[file.slice(0, -5)] = JSON.parse(read(`lib/locales/${file}`));
}
const languages = ["en", "zh", "de", "fr", "es", "ja", "ko", "pt"];
if (languages.some(id => !dictionaries[id]) || Object.keys(dictionaries).length !== languages.length) throw new Error("All eight locale dictionaries are required");
const placeholders = value => [...value.matchAll(/\{(\w+)\}/g)].map(match => match[1]).sort();
const keys = Object.keys(dictionaries.en).sort();
for (const [id, dictionary] of Object.entries(dictionaries)) {
  if (JSON.stringify(Object.keys(dictionary).sort()) !== JSON.stringify(keys)) throw new Error(`Locale key mismatch: ${id}`);
  for (const key of keys) {
    if (typeof dictionary[key] !== "string" || !dictionary[key].trim()) throw new Error(`Missing translation: ${id}.${key}`);
    if (JSON.stringify(placeholders(dictionary[key])) !== JSON.stringify(placeholders(dictionaries.en[key]))) throw new Error(`Locale placeholders differ: ${id}.${key}`);
  }
}
const model = read("lib/model.cjs").trim();
let source = read("src/client.js");
source = source.replace("__ENHANCEMENTS_MODEL__", () => `(() => { const module = { exports: {} };\n${model}\nreturn module.exports; })()`);
source = source.replace("__ENHANCEMENTS_LOCALES__", () => JSON.stringify(dictionaries, null, 2));
const output = "// Generated by scripts/build-client.mjs from src/client.js, lib/model.cjs and lib/locales.\n" + source;
const target = new URL("lib/client.js", root);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) throw new Error("Client bundle is stale: run npm run build");
} else {
  writeFileSync(target, output);
}
console.log(`${process.argv.includes("--check") ? "Checked" : "Built"} ${fileURLToPath(target)}`);
