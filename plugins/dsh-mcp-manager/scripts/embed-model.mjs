#!/usr/bin/env node
/**
 * Single sources of truth:
 *   - lib/model.cjs        pure rules (Node Host, tests, browser)
 *   - lib/locales/*.json   UI dictionaries (browser; tests check key parity)
 * DSH serves only the package's "./client" entry to the browser, so this script
 * inlines both into lib/client.js between BEGIN/END markers, inside the main
 * ModuleLoader factory. It must not register a second ModuleLoader id: DSH
 * re-executes the client bundle on live patch reload and only invalidates the
 * package's own id, so a second id throws "duplicate factory registration".
 *
 *   node scripts/embed-model.mjs           rewrite lib/client.js
 *   node scripts/embed-model.mjs --check   exit 1 when lib/client.js is stale
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const clientPath = join(root, "lib/client.js");
const LOCALE_ORDER = ["en", "zh", "de", "fr", "es", "ja", "ko", "pt"];

function marker(kind) {
  return {
    begin: `// BEGIN EMBEDDED ${kind} (generated by scripts/embed-model.mjs from lib/${kind === "MODEL" ? "model.cjs" : "locales/*.json"} — do not edit)`,
    end: `// END EMBEDDED ${kind}`,
  };
}

export function modelBlock(source) {
  const { begin, end } = marker("MODEL");
  return [
    "\t\t" + begin,
    "\t\tconst model = (() => {",
    "\t\t\tconst module = { exports: {} };",
    "\t\t\tconst exports = module.exports;",
    source.replace(/\r\n/g, "\n").trim(),
    "\t\t\treturn module.exports;",
    "\t\t})();",
    "\t\t" + end,
  ].join("\n");
}

export function localesBlock(locales) {
  const { begin, end } = marker("LOCALES");
  return ["\t\t" + begin, "\t\tconst LOCALES = " + JSON.stringify(locales, null, "\t") + ";", "\t\t" + end].join("\n");
}

function replaceBlock(client, kind, block, placeholder) {
  const { begin, end } = marker(kind);
  const beginAt = client.indexOf("\t\t" + begin);
  if (beginAt !== -1) {
    const endAt = client.indexOf(end, beginAt);
    if (endAt === -1) throw new Error(`END ${kind} marker missing`);
    return client.slice(0, beginAt) + block + client.slice(endAt + end.length);
  }
  if (!placeholder.test(client)) throw new Error(`no ${kind} markers and no placeholder ${placeholder}`);
  return client.replace(placeholder, () => block);
}

export function readLocales() {
  const dir = join(root, "lib/locales");
  const files = readdirSync(dir).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5));
  const ids = [...LOCALE_ORDER.filter((id) => files.includes(id)), ...files.filter((id) => !LOCALE_ORDER.includes(id)).sort()];
  const out = {};
  for (const id of ids) out[id] = JSON.parse(readFileSync(join(dir, id + ".json"), "utf8"));
  return out;
}

export function render(client) {
  client = client.replace(/\r\n/g, "\n");
  const main = client.indexOf('window.__ModuleLoader__.load({\n\tid: "dsh-mcp-manager",');
  if (main === -1) throw new Error("main ModuleLoader for dsh-mcp-manager not found");
  client = client.slice(main);
  const model = readFileSync(join(root, "lib/model.cjs"), "utf8");
  if (!model.includes("module.exports")) throw new Error("model.cjs must assign module.exports");
  client = replaceBlock(client, "MODEL", modelBlock(model), /^[\t ]*const model = require\("dsh-mcp-manager\/model"\);[^\n]*$/m);
  client = replaceBlock(client, "LOCALES", localesBlock(readLocales()), /^[\t ]*const LOCALES = \{\};[^\n]*$/m);
  return client;
}

if (process.argv[1] && process.argv[1].endsWith("embed-model.mjs")) {
  const current = readFileSync(clientPath, "utf8");
  const next = render(current);
  if (process.argv.includes("--check")) {
    if (next !== current) { console.error("lib/client.js is stale: run node scripts/embed-model.mjs"); process.exit(1); }
    console.log("embed up to date");
  } else {
    writeFileSync(clientPath, next);
    console.log("embedded lib/model.cjs and lib/locales/*.json into lib/client.js");
  }
}
